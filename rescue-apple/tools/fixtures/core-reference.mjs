// -0/NaN/±Infinity as the exporter's strings). Usage: node rescue-apple/tools/fixtures/core-reference.mjs
import fs from 'node:fs';
import path from 'node:path';
import { gameImport } from '../export/shims/loader.mjs';
import { APPLE, num } from '../export/lib/common.mjs';

const N = (a) => Array.from(a, num);
const { FeatureSet } = await gameImport('systems/ocean/features.js');
const { snapQuantum, buildOceanGrid } = await gameImport('systems/ocean/grid.js');

// ---- FeatureSet script: set / update / downwash / remove / evict, sampled heightAt + flowAt + packing
const fset = new FeatureSet();
const pts = [[0, 0, 0], [12.5, -3, 0], [40, 22, 0.5], [-30, 18, 0], [100, -60, 1.25], [7.3, 7.3, 0]];
const out = [];
const sample = (label) => {
  const h = pts.map(([x, z, t]) => fset.heightAt(x, z, t));
  const f = pts.flatMap(([x, z]) => { const o = { x: 0, y: 0, set(a, b) { this.x = a; this.y = b; return this; } }; fset.flowAt(x, z, o); return [o.x, o.y]; });
  out.push({ label, count: fset.count, active: fset.active, residual: num(fset.residual), h: N(h), f: N(f), uA: N(fset.uA), uB: N(fset.uB), uC: N(fset.uC) });
};
fset.set('r1', { type: 'rogue', x: 10, z: -5, dir: { x: 0.6, y: 0.8 }, width: 30, length: 400, speed: 12, height: 9, strength: 0.9 });
fset.set('v1', { type: 'vortex', x: -20, z: 15, radius: 30, strength: 0.8 });
fset.set('w1', { type: 'whirlpool', x: 35, z: 20 });
sample('after set');
for (let i = 0; i < 30; i++) fset.update(1 / 60);
sample('after 0.5 s');
fset.setDownwash(7.3, 7.3, 9.123456789, 0.7);
sample('downwash');
fset.remove('r1');
for (let i = 0; i < 60; i++) fset.update(1 / 60);
sample('rogue removed +1 s');
fset.set('x', { type: 'bogus' });
fset.set('v2', { type: 'vortex', x: 1, z: 2, spin: 1, strength: 3 });
fset.set('w2', { type: 'whirlpool', x: -5, z: -6, radius: 12, strength: 0.5 });
sample('evict');
for (let i = 0; i < 120; i++) fset.update(1 / 30);
sample('after 4 s');

// ---- ocean grid: snapQuantum + position/index checksums
const grid = [160, 224, 300].map((n) => {
  const g = buildOceanGrid(n);
  const p = g.attributes.position.array, idx = g.index.array;
  let pw = 0;
  for (let i = 0; i < p.length; i++) pw += p[i] * ((i % 7) + 1);
  let is = 0, iw = 0;
  for (let i = 0; i < idx.length; i++) { is += idx[i]; iw = (iw * 31 + idx[i]) >>> 0; }
  return { N: n, q: num(snapQuantum(n)), verts: p.length / 3, idx: idx.length, pw: num(pw), is, iw };
});

const fmt = (o) => JSON.stringify(o);
let s = '// GENERATED by tools/fixtures/core-reference.mjs — Node 22 running the web modules\n';
s += '// (systems/ocean/features.js, systems/ocean/grid.js). Regenerate after web changes; replaced by\n';
s += '// Tests/Vectors/ocean/features.json and grid.json once the exporter ships them (PLAN §5.3).\n';
s += 'enum CoreReference {\n';
s += '  static let featureSetJSON = #"""\n' + fmt({ pts, script: out }) + '\n"""#\n\n';
s += '  static let oceanGridJSON = #"""\n' + fmt(grid) + '\n"""#\n';
s += '}\n';
const dst = path.join(APPLE, 'Tests/MaydayCoreTests/Support/CoreReference.swift');
fs.writeFileSync(dst, s);
console.log(dst, s.length);
