// Generates Core/Sources/MaydayCore/Weather/Palette+Fields.swift (the typed, contract-shaped palette and
// its unpack()) from the exported layout in Resources/Data/palette.json (weather/palette.js LAYOUT).
// Re-run after the web palette layout changes: node rescue-apple/tools/codegen/palette-swift.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const APPLE = fileURLToPath(new URL('../../', import.meta.url));
const pal = JSON.parse(fs.readFileSync(path.join(APPLE, 'Resources/Data/palette.json'), 'utf8')).data['weather/palette'];
const L = pal.LAYOUT;
const GROUPS = { post: 'Post', sea: 'Sea', detect: 'Detect' };
const typeOf = (k) => (k === 'color' ? 'PaletteColor' : k === 'vec3' ? 'V3' : 'Double');
const initOf = (k) => (k === 'color' ? 'PaletteColor()' : k === 'vec3' ? 'V3()' : '0');
const ref = (e) => (e.group ? `${e.group}.${e.key}` : e.key);

let s = '';
s += '// GENERATED by tools/codegen/palette-swift.mjs from Resources/Data/palette.json (weather/palette.js\n';
s += `// LAYOUT, ${L.length} entries, ${pal.SLOTS} slots). Do not edit by hand.\n\n`;
s += 'extension Palette {\n';
s += '  /// weather/palette.js LAYOUT: [key, kind, channel, group] with packed offsets.\n';
s += '  public static let layout: [PaletteEntry] = [\n';
for (const e of L) s += `    PaletteEntry(key: "${e.key}", kind: .${e.kind}, ch: ${e.ch}, group: "${e.group}", o: ${e.o}, size: ${e.size}),\n`;
s += '  ]\n\n';
s += `  public static let slots = ${pal.SLOTS}\n\n`;
s += '  /// unpack(p, a): write a packed array into the palette (colours stay linear).\n';
s += '  public mutating func unpack(_ a: [Double]) {\n';
s += `    precondition(a.count >= Palette.slots, "Palette.unpack: packed array too short")\n`;
for (const e of L) {
  const o = e.o;
  if (e.kind === 'color') s += `    ${ref(e)} = PaletteColor(a[${o}], a[${o + 1}], a[${o + 2}])\n`;
  else if (e.kind === 'vec3') s += `    ${ref(e)} = V3(a[${o}], a[${o + 1}], a[${o + 2}])\n`;
  else if (e.kind === 'angle') s += `    ${ref(e)} = Palette.angleDegrees(a[${o}], a[${o + 1}])\n`;
  else s += `    ${ref(e)} = a[${o}]\n`;
}
s += '    // Rain makes the sea matte (squall «матовое олово», §2.6.3): fold the rain term in once.\n';
s += '    sea.roughness = sea.roughness + sea.roughnessRain * rain\n';
s += '  }\n\n';
s += '  /// Components of one entry by group and key ("" / "sky", "sea" / "Hs"); nil for an unknown key.\n';
s += '  public func components(group: String, key: String) -> [Double]? {\n';
s += '    switch (group, key) {\n';
for (const e of L) {
  const r = ref(e);
  const v = e.kind === 'color' ? `[${r}.r, ${r}.g, ${r}.b]` : e.kind === 'vec3' ? `[${r}.x, ${r}.y, ${r}.z]` : `[${r}]`;
  s += `    case ("${e.group}", "${e.key}"): return ${v}\n`;
}
s += '    default: return nil\n';
s += '    }\n';
s += '  }\n';
s += '}\n\n';
for (const [g, T] of Object.entries(GROUPS)) {
  s += `extension Palette {\n  /// palette.${g}\n  public struct ${T}: Equatable, Sendable {\n`;
  for (const e of L.filter((x) => x.group === g)) s += `    public var ${e.key}: ${typeOf(e.kind)} = ${initOf(e.kind)}\n`;
  s += '    public init() {}\n  }\n}\n\n';
}
s += '/// Contract-shaped palette (weather/palette.js createPalette/unpack; DESIGN §2.3).\n';
s += 'public struct Palette: Equatable, Sendable {\n';
for (const [g, T] of Object.entries(GROUPS)) s += `  public var ${g} = ${T}()\n`;
for (const e of L.filter((x) => !x.group)) s += `  public var ${e.key}: ${typeOf(e.kind)} = ${initOf(e.kind)}\n`;
s += '  public init() {}\n}\n';

const dst = path.join(APPLE, 'Core/Sources/MaydayCore/Weather/Palette+Fields.swift');
fs.writeFileSync(dst, s);
console.log(dst, L.length, 'entries');
