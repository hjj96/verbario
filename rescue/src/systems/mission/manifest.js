/**
 * Pick a quote for a person. Prefers the most specific matching tag; avoids repeats via `used`.
 * @param person {gender}
 * @param tags   array of context tags (most specific first)
 */
export function quoteFor(rng, person, tags, used) {
  const f = person && person.gender === 'f';
  for (const tag of tags) {
    const pool = QUOTES.filter((q) => q[0].includes(tag) && !used.has(q[1]));
    if (pool.length && (tag === 'any' || rng.next() < 0.75)) {
      const q = rng.pick(pool);
      used.add(q[1]);
      return f && q[2] ? q[2] : q[1];
    }
  }
  const any = QUOTES.filter((q) => q[0].includes('any'));
  const q = rng.pick(any);
  return f && q[2] ? q[2] : q[1];
}

// Condition label from warmth at lift (survivors may already provide one).
export function conditionFor(warmth, injured) {
  if (injured) return 'травма';
  if (warmth == null) return 'стабильное';
  if (warmth < 0.3) return 'сильное переохлаждение';
  if (warmth < 0.6) return 'переохлаждение';
  return 'стабильное';
}

