function pickWeighted(rng, list, gender) {
  const ok = list.filter((j) => (gender === 'm' ? j[0] : j[1]));
  let sum = 0;
  for (const j of ok) sum += j[2];
  let r = rng.next() * sum;
  for (const j of ok) {
    r -= j[2];
    if (r <= 0) return j;
  }
  return ok[ok.length - 1];
}

/**
 * Generate `count` people for a group.
 * @param rng      seeded rng from core/math.js createRng
 * @param theme    key of THEMES
 * @param opts     { lead: [masc, fem] fixed first occupation (e.g. pilot), used: Set of names to avoid duplicates }
 */
export function makePeople(rng, theme, count, opts = {}) {
  const T = THEMES[theme] || THEMES.generic;
  const used = opts.used || new Set();
  const out = [];
  for (let i = 0; i < count; i++) {
    let gender = rng.next() < T.female ? 'f' : 'm';
    let job;
    if (i === 0 && opts.lead) {
      job = [opts.lead[0], opts.lead[1] || opts.lead[0], 1];
      if (!opts.lead[1]) gender = 'm';
    } else job = pickWeighted(rng, T.jobs, gender);
    if (!job) {
      gender = gender === 'm' ? 'f' : 'm';
      job = pickWeighted(rng, T.jobs, gender);
    }
    const spec = job[3] || {};
    const child = !!spec.child;
    const age = child ? rng.int(7, 13) : rng.int(spec.min || 19, spec.max || 66);
    let first, surname, name;
    for (let tries = 0; tries < 8; tries++) {
      first = child ? rng.pick(gender === 'f' ? CHILD_F : CHILD_M) : rng.pick(gender === 'f' ? FIRST_F : FIRST_M);
      const base = rng.pick(SURNAMES);
      surname = gender === 'f' ? feminize(base) : base;
      name = `${first} ${surname}`;
      if (!used.has(name)) break;
    }
    used.add(name);
    out.push({ name, first, surname, gender, age, child, occupation: gender === 'f' ? job[1] : job[0] });
  }
  return out;
}

// Guess grammatical gender from a first name (records produced by other systems may lack it).
export function guessGender(name) {
  const first = String(name || '').trim().split(/\s+/)[0] || '';
  if (/(а|я)$/.test(first) && !/^(Илья|Никита|Савва|Лука|Фома|Кузьма|Миша|Ваня|Тёма|Сёма|Лёва|Костя|Петя|Саша)$/.test(first)) return 'f';
  return 'm';
}

